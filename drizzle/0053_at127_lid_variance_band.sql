CREATE OR REPLACE VIEW v_weekly_variance AS
WITH lines AS (
  SELECT
    l.stock_take_id,
    i.is_lid,
    l.expected,
    ABS(l.counted - l.expected) AS abs_delta,
    CASE
      WHEN l.expected <= 0 THEN CASE WHEN l.counted = 0 THEN 0 ELSE 100 END
      ELSE ABS(l.counted - l.expected)::numeric * 100 / l.expected
    END AS line_pct
  FROM stock_take_lines l
  JOIN inventory_lots lot ON lot.id = l.inventory_lot_id
  JOIN inventory_items i ON i.id = lot.inventory_item_id
  WHERE l.counted IS NOT NULL
),
takes AS (
  SELECT
    st.id,
    date_trunc(
      'week',
      (st.completed_at AT TIME ZONE 'Africa/Johannesburg')
    )::date AS week_starting,
    COALESCE(
      (SELECT (c.value ->> 'lid')::numeric FROM app_config c
        WHERE c.tenant_id = st.tenant_id AND c.key = 'variance_bands'),
      25
    ) AS lid_band_pct,
    (SELECT CASE WHEN COUNT(*) = 0 THEN NULL ELSE COALESCE(ROUND(
              SUM(ln.abs_delta) FILTER (WHERE ln.expected > 0) * 100.0
              / NULLIF(SUM(ln.expected) FILTER (WHERE ln.expected > 0), 0)
            ), 0)::integer END
       FROM lines ln WHERE ln.stock_take_id = st.id AND NOT ln.is_lid) AS other_pct,
    (SELECT COUNT(*) FROM lines ln WHERE ln.stock_take_id = st.id AND ln.is_lid) AS lid_lines,
    (SELECT MAX(ln.line_pct) FROM lines ln WHERE ln.stock_take_id = st.id AND ln.is_lid) AS lid_max_pct
  FROM stock_takes st
  WHERE st.completed_at IS NOT NULL
)
SELECT
  week_starting,
  COUNT(*)                                              AS stock_take_count,
  ROUND(AVG(other_pct), 2)                              AS avg_abs_variance_pct,
  MAX(other_pct)                                        AS max_abs_variance_pct,
  COALESCE(bool_or(other_pct >= 5), false)              AS breaches_threshold,
  SUM(lid_lines)::bigint                                AS lid_line_count,
  ROUND(MAX(lid_max_pct), 2)                            AS max_lid_variance_pct,
  MAX(lid_band_pct)                                     AS lid_band_pct,
  COALESCE(bool_or(lid_max_pct > lid_band_pct), false)  AS lid_breaches_band
FROM takes
GROUP BY week_starting;
